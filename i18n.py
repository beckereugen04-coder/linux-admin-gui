"""Mehrsprachigkeit (Deutsch/English) für Oberfläche und Meldungen.

t("schluessel", name=...) liefert den Text in der aktuellen Sprache.
Ist ein Schlüssel in der Sprache nicht vorhanden, wird Deutsch verwendet.
"""

LANGUAGES = {"de": "Deutsch", "en": "English"}
LANG = "de"


def set_language(code):
    global LANG
    LANG = code if code in LANGUAGES else "de"


def t(key, **kw):
    entry = CATALOG.get(key)
    if entry is None:
        return key
    text = entry.get(LANG) or entry.get("de") or key
    return text.format(**kw) if kw else text


def _e(de, en):
    return {"de": de, "en": en}


